"""`guard install` / `guard uninstall`: wire every detected agent on this machine.

Install is idempotent: run it again after adding a rule, skill or adapter.
Everything it replaces is backed up first (state.InstallState).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from agent_guard import adapters as ad
from agent_guard import skills
from agent_guard.paths import contract, expand, git_hooks_dir, guard_bin, repo_root, state_home
from agent_guard.state import InstallState, remove_path, symlink

GIT_HOOKS = [
    "applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit", "pre-merge-commit",
    "prepare-commit-msg", "commit-msg", "post-commit", "pre-rebase", "post-checkout", "post-merge",
    "pre-push", "pre-auto-gc", "post-rewrite", "sendemail-validate", "post-index-change",
    "push-to-checkout", "reference-transaction",
]

WRAPPER = """#!/bin/sh
# agent-guard runtime (generated by `guard install`; edit the repo, not this file)
unset PYTHONHOME
PYTHONPATH="{src}" exec "{python}" -s -m agent_guard "$@"
"""


def _git_global(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", "config", "--global", *args], capture_output=True, text=True)


def install_runtime(state: InstallState, log: list[str]) -> None:
    gb = guard_bin()
    gb.parent.mkdir(parents=True, exist_ok=True)
    gb.write_text(WRAPPER.format(src=repo_root() / "src", python=sys.executable), encoding="utf-8")
    gb.chmod(0o755)
    if symlink(expand("~/.local/bin/guard"), gb, state):
        log.append("linked ~/.local/bin/guard")

    hooks = git_hooks_dir()
    hooks.mkdir(parents=True, exist_ok=True)
    tpl = (repo_root() / "git-hooks" / "dispatcher").read_text(encoding="utf-8")
    disp = hooks / "_dispatcher"
    disp.write_text(tpl.replace("__GUARD_BIN__", str(gb)), encoding="utf-8")
    disp.chmod(0o755)
    for name in GIT_HOOKS:
        link = hooks / name
        if not (link.is_symlink() and os.readlink(link) == "_dispatcher"):
            remove_path(link)
            os.symlink("_dispatcher", link)

    current = _git_global("--get", "core.hooksPath").stdout.strip()
    if "git_hooks_path_prev" not in state.data:
        state.data["git_hooks_path_prev"] = current or None
        state.save()
    if current != str(hooks):
        if current:
            log.append(f"note: replaced previous global core.hooksPath {current} (restored on uninstall)")
        _git_global("core.hooksPath", str(hooks))
        log.append(f"git: global core.hooksPath -> {contract(hooks)} (every repo on this machine)")


def install(dry_run: bool = False) -> list[str]:
    log: list[str] = []
    state = InstallState()
    adapters = ad.load_all()
    target = repo_root() / "global" / "AGENTS.md"
    if not dry_run:
        install_runtime(state, log)

    for a in adapters:
        if not a.detected():
            log.append(f"skip {a.title}: not installed")
            continue
        for p in map(expand, a.instructions):
            if p.is_symlink() and Path(os.readlink(p)) == target:
                continue
            if p.is_file() and not p.is_symlink() and p.read_text(encoding="utf-8", errors="replace").strip():
                log.append(f"{a.title}: existing {contract(p)} backed up before linking; merge anything you "
                           "still want into global/AGENTS.md")
            log.append(f"{a.title}: {contract(p)} -> global/AGENTS.md")
            if not dry_run:
                symlink(p, target, state)
        msg = ad.install_hooks(a, state, dry_run=dry_run)
        if msg:
            log.append(f"{a.title}: {msg}")
    log += skills.sync(adapters, state, dry_run=dry_run)
    if not dry_run:
        state.save()
    return log


def uninstall(purge: bool = False) -> list[str]:
    log: list[str] = []
    state = InstallState()
    for a in ad.load_all():
        msg = ad.uninstall_hooks(a, state)
        if msg:
            log.append(f"{a.title}: {msg}")
        key = str(expand(a.hooks_file)) if a.hooks_file else None
        if key and key in state.originals and a.hooks_writer not in ad.OWNED_FILE_WRITERS:
            del state.originals[key]  # stripped in place; keep any later edits the user made
            state.save()

    prev = state.data.get("git_hooks_path_prev")
    if prev:
        _git_global("core.hooksPath", prev)
        log.append(f"git: core.hooksPath restored to {prev}")
    elif _git_global("--get", "core.hooksPath").stdout.strip() == str(git_hooks_dir()):
        _git_global("--unset", "core.hooksPath")
        log.append("git: global core.hooksPath unset")

    # Restore deepest paths first (links inside dirs before the dirs themselves).
    created = {d for o in state.originals.values() for d in o.get("created_dirs", [])}
    for key in sorted(state.originals, key=lambda k: -k.count("/")):
        log.append(state.restore(key))
    for d in sorted(created, key=lambda k: -k.count("/")):  # folders install created, if now empty
        try:
            Path(d).rmdir()
        except OSError:
            pass
    shutil.rmtree(git_hooks_dir(), ignore_errors=True)
    if guard_bin().exists():
        remove_path(guard_bin())
    state.data.pop("git_hooks_path_prev", None)
    state.save()
    if purge:
        shutil.rmtree(state_home(), ignore_errors=True)
        log.append(f"removed {contract(state_home())} (logs, backups, venv)")
    return log
